char ans[10][100];

void sol() {
    string c1,c2;
    cin>>c1>>c2;
    char base=c2[0];
    int curx=0,cury=0;
    for(int i=0;i<c1.size();i++){
        if(c1[i]!='E'){
            int del=c1[i]-'A';
            for(int n=0;n<5;n++){
                for(int m=0;m<5;m++){
                    if(All[del][n][m]){
                        ans[n][cury+m]=base;
                    }else{
                        ans[n][cury+m]='.';
                    }
                }
            }
            cury+=5;
            for(int n=0;n<5;n++){
                ans[n][cury]='.';
            }
            cury+=1;
        }else{
            for(int n=0;n<5;n++){
                for(int j=0;j<c2.size();j++){
                    if(n==0||n==4||n==2) ans[n][cury+j]=c2[j];
                    else if(j==0) ans[n][cury+j]=base;
                    else ans[n][cury+j]='.';
                }
            }
            cury+=c2.size();
            for(int n=0;n<5;n++){
                ans[n][cury]='.';
            }
            cury+=1;
        }
    }
    for(int i=0;i<5;i++){
        for(int j=0;j<cury;j++){
            cout<<ans[i][j];
        }
        cout<<'\n';
    }
}

